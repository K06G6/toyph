#!/usr/bin/env python3
"""Generate a minimal bitmap font JSON file for Toyph.

Each glyph is 5 pixels wide and 11 pixels tall.
Pixels is a flat row-major array of length 55 (5*11).
Values are 0 (off) or 4095 (on).
Character shapes use roughly the top 8 rows; bottom 3 rows are empty.
"""

import json
import os

ON = 4095
OFF = 0

def bitmap(rows):
    """Convert a list of 5-char strings into a flat pixel array.

    Each string represents one row. '#' = ON, '.' = OFF.
    Pads to 11 rows (55 pixels) with empty rows at the bottom.
    """
    assert len(rows) <= 11, f"Too many rows: {len(rows)}"
    pixels = []
    for r in rows:
        assert len(r) == 5, f"Row wrong width: '{r}' (len {len(r)})"
        for ch in r:
            pixels.append(ON if ch == '#' else OFF)
    # Pad remaining rows with OFF
    while len(pixels) < 55:
        pixels.append(OFF)
    return pixels


